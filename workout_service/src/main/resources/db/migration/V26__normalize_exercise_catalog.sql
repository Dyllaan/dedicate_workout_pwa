UPDATE exercise_info child
SET parent_id = parent_lookup.id
FROM exercise_info parent_lookup
WHERE child.parent_id IS NOT NULL
  AND NOT EXISTS (
      SELECT 1
      FROM exercise_info existing_parent
      WHERE existing_parent.id = child.parent_id
  )
  AND parent_lookup.equipment_id = child.equipment_id
  AND LOWER(parent_lookup.name) = LOWER(
      regexp_replace(
          split_part(child.name, ':', 1),
          '\\s*\\(.*\\)\\s*$',
          '',
          'g'
      )
  )
  AND COALESCE(NULLIF(parent_lookup.variation, ''), 'No') = 'No';

INSERT INTO exercise_info_muscles (exercise_info_id, muscle_role, muscle_group_id)
WITH muscle_rows AS (
    SELECT ei.id AS exercise_info_id, 'TARGET' AS muscle_role, TRIM(token) AS muscle_name
    FROM exercise_info ei
    CROSS JOIN LATERAL regexp_split_to_table(COALESCE(ei.target_muscles, ''), ',') AS token
    WHERE TRIM(token) <> ''
      AND LOWER(TRIM(token)) <> 'none'
    UNION ALL
    SELECT ei.id, 'SYNERGIST', TRIM(token)
    FROM exercise_info ei
    CROSS JOIN LATERAL regexp_split_to_table(COALESCE(ei.synergist_muscles, ''), ',') AS token
    WHERE TRIM(token) <> ''
      AND LOWER(TRIM(token)) <> 'none'
    UNION ALL
    SELECT ei.id, 'STABILIZER', TRIM(token)
    FROM exercise_info ei
    CROSS JOIN LATERAL regexp_split_to_table(COALESCE(ei.stabilizer_muscles, ''), ',') AS token
    WHERE TRIM(token) <> ''
      AND LOWER(TRIM(token)) <> 'none'
    UNION ALL
    SELECT ei.id, 'ANTAGONIST', TRIM(token)
    FROM exercise_info ei
    CROSS JOIN LATERAL regexp_split_to_table(COALESCE(ei.antagonist_muscles, ''), ',') AS token
    WHERE TRIM(token) <> ''
      AND LOWER(TRIM(token)) <> 'none'
    UNION ALL
    SELECT ei.id, 'DYNAMIC_STABILIZER', TRIM(token)
    FROM exercise_info ei
    CROSS JOIN LATERAL regexp_split_to_table(COALESCE(ei.dynamic_stabilizer_muscles, ''), ',') AS token
    WHERE TRIM(token) <> ''
      AND LOWER(TRIM(token)) <> 'none'
    UNION ALL
    SELECT ei.id, 'SECONDARY', TRIM(token)
    FROM exercise_info ei
    CROSS JOIN LATERAL regexp_split_to_table(COALESCE(ei.secondary_muscles, ''), ',') AS token
    WHERE TRIM(token) <> ''
      AND LOWER(TRIM(token)) <> 'none'
)
SELECT
    muscle_rows.exercise_info_id,
    muscle_rows.muscle_role,
    muscle_lookup.id
FROM muscle_rows
JOIN exercise_catalog_muscle_group muscle_lookup
    ON LOWER(muscle_rows.muscle_name) = LOWER(muscle_lookup.name)
ON CONFLICT (exercise_info_id, muscle_role, muscle_group_id) DO NOTHING;

