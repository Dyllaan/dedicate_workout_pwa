WITH muscle_tokens AS (
    SELECT
        LOWER(TRIM(token_text)) AS normalized_name,
        TRIM(token_text) AS muscle_name,
        ei.id AS source_id,
        token_row.ordinality AS token_ordinal
    FROM exercise_info ei
    CROSS JOIN LATERAL (
        VALUES
            (ei.main_muscle),
            (ei.target_muscles),
            (ei.synergist_muscles),
            (ei.stabilizer_muscles),
            (ei.antagonist_muscles),
            (ei.dynamic_stabilizer_muscles),
            (ei.secondary_muscles)
    ) AS source(raw_muscle)
    CROSS JOIN LATERAL regexp_split_to_table(COALESCE(source.raw_muscle, ''), ',') WITH ORDINALITY AS token_row(token_text, ordinality)
    WHERE TRIM(token_text) <> ''
      AND LOWER(TRIM(token_text)) <> 'none'
)
INSERT INTO exercise_catalog_muscle_group (name)
SELECT DISTINCT ON (normalized_name) muscle_name
FROM muscle_tokens
ORDER BY normalized_name, source_id, token_ordinal
ON CONFLICT (name) DO NOTHING;

